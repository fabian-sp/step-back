## Squared loss
#==========================================================

x1 = torch.arange(10).float()
x2 = torch.flip(x1, dims=(0,))
x1.requires_grad_(True)


def test_mse_loss():

    loss_fn = Loss(name='squared', backwards=True)
    L = loss_fn.compute(x1, x2)

    assert_close(L, torch.tensor(33.))
    assert_close(x1.grad, (2/len(x1))*(x1-x2))

    return


